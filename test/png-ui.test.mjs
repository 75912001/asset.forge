import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {mountAssetEditor} from '../public/editor/asset-editor.mjs';
const ref='images/'+'b'.repeat(64)+'.png';
const html=await readFile(new URL('../public/editor/index.html',import.meta.url),'utf8');

test('装备名称随图标文件名更新且禁止手动输入, 取消或失败保留名称',async t=>{
  const previousDocument=globalThis.document;t.after(()=>globalThis.document=previousDocument);
  const elements=new Map([...html.matchAll(/\bid="([^"]+)"/g)].map(match=>[match[1],{value:'',listeners:{},classList:{toggle(){}},addEventListener(name,handler){this.listeners[name]=handler;},querySelector:()=>null,querySelectorAll:()=>[]}]));
  globalThis.document={getElementById:id=>elements.get(id),querySelectorAll:()=>[]};
  const fields=[{key:'id',label:'ID',type:'uint32',required:true},{key:'name',label:'名称',type:'string',required:true},{key:'icon',label:'图标',type:'png',required:false}];
  const workspace={categories:[{key:'equipment',name:'装备',start:1,end:9}],enums:[],tables:{equipment:{fields,rows:[{id:1,name:'旧名称',icon:null}]}}};
  let selected='icons/weapons/青龙偃月刀.png',fail=false;
  const editor=mountAssetEditor({getWorkspace:()=>workspace,commit:async(key,table)=>{workspace.tables[key]=table;return true;},onDirty(){},onOpen(){},notify(){},onSelectPng:async()=>{if(fail)throw new Error('选择失败');return selected;}});
  const target={dataset:{record:'0',column:'2',pngSelect:''},closest:selector=>selector==='[data-png-select]'?target:null};
  await elements.get('asset-data-rows').listeners.click({target});
  assert.equal(editor.snapshot().draft.rows[0].name,'青龙偃月刀');
  assert.match(elements.get('asset-data-rows').innerHTML,/<input[^>]*aria-label="名称 · 第 1 行"[^>]*readonly/);
  const input={dataset:{record:'0',column:'1'},value:'自定义名称',closest:()=>input};
  elements.get('asset-data-rows').listeners.input({target:input});
  assert.equal(editor.snapshot().draft.rows[0].name,'青龙偃月刀');
  selected='装备/倚天剑-2.PNG';await elements.get('asset-data-rows').listeners.click({target});
  await elements.get('asset-save').listeners.click();
  assert.equal(workspace.tables.equipment.rows[0].name,'倚天剑-2');
  selected=null;await elements.get('asset-data-rows').listeners.click({target});
  assert.equal(editor.snapshot().draft.rows[0].name,'倚天剑-2');
  fail=true;await elements.get('asset-data-rows').listeners.click({target});
  assert.equal(editor.snapshot().draft.rows[0].name,'倚天剑-2');
  const clear={dataset:{record:'0',column:'2',pngClear:''},closest:selector=>selector==='[data-png-clear]'?clear:null};
  await elements.get('asset-data-rows').listeners.click({target:clear});
  assert.equal(editor.snapshot().draft.rows[0].name,'');
  assert.equal(editor.snapshot().draft.rows[0].icon,null);
  assert.equal(workspace.tables.equipment.rows[0].name,'倚天剑-2');
});
test('PNG cells select original resources, preview and save paths; failed replacement preserves the previous reference',async t=>{
  const previousDocument=globalThis.document;t.after(()=>globalThis.document=previousDocument);
  const elements=new Map([...html.matchAll(/\bid="([^"]+)"/g)].map(match=>[match[1],{value:'',listeners:{},classList:{toggle(){}},addEventListener(name,handler){this.listeners[name]=handler;},querySelector:()=>null,querySelectorAll:()=>[]}]));
  globalThis.document={getElementById:id=>elements.get(id),querySelectorAll:()=>[]};
  const workspace={categories:[{key:'base',name:'基础数值',start:0,end:9}],enums:[],tables:{base:{fields:[{key:'id',label:'ID',type:'uint32',required:true},{key:'icon',label:'图标',type:'png',required:false},{key:'name',label:'名称',type:'string',required:false}],rows:[{id:1,icon:null,name:'原名称'}]}}};
  let complete,fail=false,saves=0;
  const editor=mountAssetEditor({getWorkspace:()=>workspace,commit:async(key,table)=>{workspace.tables[key]=table;saves++;return true;},onDirty(){},onOpen(){},notify(){},onSelectPng:async()=>{if(fail)throw new Error('offline');await new Promise(resolve=>complete=resolve);return ref;}});
  assert.match(elements.get('asset-data-rows').innerHTML,/data-png-select/);
  assert.doesNotMatch(elements.get('asset-data-rows').innerHTML,/type="file"/);
  const nameInput={dataset:{record:'0',column:'2'},value:'金币',closest:()=>nameInput};
  elements.get('asset-data-rows').listeners.input({target:nameInput});
  assert.equal(editor.snapshot().draft.rows[0].name,'金币');
  const target={dataset:{record:'0',column:'1',pngSelect:''},closest:()=>target};
  const pending=elements.get('asset-data-rows').listeners.click({target});
  assert.equal(editor.hasUnsaved(),true);
  await elements.get('asset-save').listeners.click();assert.equal(saves,0,'save must wait for an in-flight PNG upload');
  complete();await pending;
  assert.equal(editor.snapshot().draft.rows[0].icon,ref);
  assert.equal(editor.snapshot().draft.rows[0].name,'金币');
  assert.match(elements.get('asset-data-rows').innerHTML,/<img[^>]+\/api\/images/);
  await elements.get('asset-save').listeners.click();assert.equal(workspace.tables.base.rows[0].icon,ref);
  fail=true;await elements.get('asset-data-rows').listeners.click({target});
  assert.equal(editor.snapshot().draft.rows[0].icon,ref);assert.match(elements.get('asset-error').textContent,/offline/);
  const clear={dataset:{pngClear:'',record:'0',column:'1'},closest:selector=>selector==='[data-png-clear]'?clear:null};
  await elements.get('asset-data-rows').listeners.click({target:clear});
  await elements.get('asset-save').listeners.click();assert.equal(workspace.tables.base.rows[0].icon,null);
});
